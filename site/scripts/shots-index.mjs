// Turns the demo captures in src/assets/shots (PNG, 2x) into WebP at 1x and 2x under public/shots, and writes
// src/components/shots.gen.ts with the URL and pixel size of each so <Shot> can set width/height and a srcset.
// Run before `vocs build` (the build script does) and after adding or replacing a capture.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = path.dirname(fileURLToPath(import.meta.url));
const IN = path.resolve(here, '../src/assets/shots');
const OUT = path.resolve(here, '../public/shots');
const GEN = path.resolve(here, '../src/components/shots.gen.ts');
fs.mkdirSync(OUT, { recursive: true });

const entries = {};
for (const file of fs.readdirSync(IN).filter(f => f.endsWith('.png')).sort()) {
  const id = file.replace(/\.png$/, '');
  const src = path.join(IN, file);
  const meta = await sharp(src).metadata();
  const w2 = meta.width, h2 = meta.height;
  const w1 = Math.round(w2 / 2), h1 = Math.round(h2 / 2);
  const out2 = path.join(OUT, `${id}@2x.webp`);
  const out1 = path.join(OUT, `${id}.webp`);
  // Only re-encode when the PNG is newer than the WebP.
  const stale = (p) => !fs.existsSync(p) || fs.statSync(p).mtimeMs < fs.statSync(src).mtimeMs;
  if (stale(out2)) await sharp(src).webp({ quality: 84 }).toFile(out2);
  if (stale(out1)) await sharp(src).resize({ width: w1 }).webp({ quality: 84 }).toFile(out1);
  entries[id] = { src: `/shots/${id}.webp`, src2x: `/shots/${id}@2x.webp`, width: w1, height: h1 };
}
const body = Object.entries(entries).map(([id, e]) => `  '${id}': ${JSON.stringify(e)},`).join('\n');
fs.writeFileSync(GEN, `// Generated by scripts/shots-index.mjs. Do not edit.\nexport type ShotEntry = { src: string; src2x: string; width: number; height: number }\nexport const SHOTS: Record<string, ShotEntry> = {\n${body}\n}\n`);
console.log(`${Object.keys(entries).length} shots → public/shots, index at src/components/shots.gen.ts`);
